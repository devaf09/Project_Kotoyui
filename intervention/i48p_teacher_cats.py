"""I48p: 先生（会話の相手役の LLM）の指摘の文を、何を指しているかで分ける決まり（I48k (b) の決まりの直し）。

I48k (b) の「語尾・形」には「ている・ていた」が入っていたが、先生の文の地の部分（「」の外）の「相手は〜と言っているから」
「〜しているみたい」に当たっていた（先生自身の話し言葉で、bot の語尾への指摘ではない）。I48p で外した。
「」『』の中（言い換えの例）だけに出た語は、どの決まりでも数えない形も持つ（outside=True）。

使い方: cats(先生の文) → 当たった分け方の名前の並び（無ければ ["その他"]）。curt(先生の文) → 素っ気ない・短いと言われたか。
"""
import re

QUOTE = re.compile(r"「[^」]*」|『[^』]*』")

# I48k (b) と同じ並び。「語尾・形」だけを直した（ている・ていた を外した）
CATS = (("主語の助詞", r"「[はがも]」"),
        ("目的語・補語の助詞", r"「(を|に|へ|で|と|から|まで)」|助詞"),
        ("語尾・形（素っ気ない・命令・硬い）", r"素っ気|そっけ|ぶっきらぼう|命令|冷た|硬い|かたい|堅い|語尾"),
        ("受け・共感が無い", r"共感|寄り添|受け止め|同意|そうなんだ|大変だね"),
        ("語の選び（「X」だと・言葉）", r"「[^」]{1,15}」(だと|より|って言うと|と言うと|を使)|難しい言葉|言葉を使|言い換"),
        ("「はい」で始める", r"「はい」|『はい』|「はい、|『はい、"),
        ("語の並び", r"順番|順序|語順|並び"),
        ("意味が通らない", r"意味が(伝わりにく|分かりにく|わかりにく|通じにく)|伝わりにくい|分かりにくい"))
OLD_END = r"素っ気|そっけ|ぶっきらぼう|命令|冷た|硬い|かたい|堅い|語尾|ている|ていた"     # I48k (b) の語尾・形（比べるためだけ）
END = CATS[2][0]
# 素っ気ない・短い（言い換えの例の外だけで見る）
CURT = r"素っ気|そっけ|ぶっきらぼう|冷た|淡々|事務的|短い|短すぎ|一言だけ"


def cats(txt, outside=False):
    t = QUOTE.sub("", txt) if outside else txt
    hit = [c for c, p in CATS if re.search(p, t)]
    return hit or ["その他"]


def curt(txt):
    return bool(re.search(CURT, QUOTE.sub("", txt)))


def counted(teacher):
    """数える先生の文か（褒め・捨てた見立ては数えない。I48k (b) と同じ）。"""
    return bool(teacher) and "経験: 相手の次の行を見てから" not in teacher and not teacher.startswith("見立てを捨てた")
